import { spawnSync } from 'node:child_process';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildVehicles } from './build-gta-vehicles.mjs';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'trainers/gta5-story');
await buildVehicles(dir);
const profiles = JSON.parse(await readFile(path.join(dir, 'profiles.json'), 'utf8'));
for (const profilePath of profiles) {
const assets = path.resolve(dir, profilePath);
const profile = JSON.parse(await readFile(path.join(assets, 'profile.json'), 'utf8'));
const out = path.join(root, 'artifacts/gta5-build', profile.titleId + '-' + profile.version);
await mkdir(out, { recursive: true });
const defs = { PLAYER_ROOT: profile.playerRoot, NETWORK_FLAG: profile.networkFlag, EXEC_END: profile.execEnd, RUN_OFFSET: profile.runOffset, FRAME_FLAGS_OFFSET: profile.frameFlagsOffset, SCRIPT_REGISTRY: profile.scriptRegistry, THREAD_TABLE: profile.threadTable, THREAD_HASH_OFFSET: profile.threadHashOffset, THREAD_STATE_OFFSET: profile.threadStateOffset, THREAD_STACK_OFFSET: profile.threadStackOffset, PROLOGUE_LENGTH: profile.prologue?.length ?? 0, PROLOGUE_FNV: profile.prologue?.fnv ?? 0, PROLOGUE_STAGE_LOCAL: profile.prologue?.stageLocal ?? 0, PROLOGUE_COMPLETE_STAGE: profile.prologue?.completeStage ?? 0 };
await writeFile(path.join(assets, 'build-profile.h'), '// Generated by build-gta-bridge.mjs; do not mix executable profiles.\n#pragma once\n' + Object.entries(defs).map(([k,v]) => '#define GTA_' + k + ' ' + v + 'ULL').join('\n') + '\n#include "native-handlers.h"\n');
const handlers = JSON.parse(await readFile(path.join(assets, 'native-addresses.json'), 'utf8'));
const menu = await readFile(path.join(dir, 'menu.c'), 'utf8');
for (const match of menu.matchAll(/\b[NV]\(([A-Z_0-9]+)/g)) if (!handlers[match[1]]) throw Error('Missing native handler: ' + match[1]);
await writeFile(path.join(assets, 'native-handlers.h'), '// Native registrations for ' + profile.titleId + ' ' + profile.version + '.\n#pragma once\n' + Object.entries(handlers).map(([name, native]) => '#define H_' + name + ' ' + native.handler + 'ULL').join('\n') + '\n');
const zig = process.env.ZIG || path.join(root, 'tools/zig-x86_64-windows-0.14.1/zig.exe');
const args = ['cc', '-DGTA_BUILD_PROFILE_HEADER=' + JSON.stringify(path.join(assets, 'build-profile.h').replaceAll('\\', '/')), '-target', 'x86_64-linux-none', '-Os', '-ffreestanding', '-fno-jump-tables', '-fno-stack-protector', '-fno-asynchronous-unwind-tables', '-fno-unwind-tables', '-fPIC', '-fvisibility=hidden', '-nostdlib', '-static', '-Wl,--build-id=none', '-Wl,-T,' + path.join(dir, 'bridge.ld'), path.join(dir, 'bridge.c'), '-o', path.join(out, 'gta-bridge.elf')];
const r = spawnSync(zig, args, { stdio: 'inherit', env: { ...process.env, ZIG_GLOBAL_CACHE_DIR: path.join(out, 'zig-cache') } });
if (r.status !== 0) throw Error('GTA bridge build failed');
const elf = await readFile(path.join(out, 'gta-bridge.elf'));
const sh = Number(elf.readBigUInt64LE(40)), shSize = elf.readUInt16LE(58), shCount = elf.readUInt16LE(60);
for (let i = 0; i < shCount; i++) {
  const at = sh + i * shSize, type = elf.readUInt32LE(at + 4);
  if ([4, 9].includes(type) && elf.readBigUInt64LE(at + 32)) throw Error('Flat bridge must not contain unresolved relocations');
}
const ph = Number(elf.readBigUInt64LE(32)), size = elf.readUInt16LE(54), count = elf.readUInt16LE(56), image = Buffer.alloc(0x20000);
for (let i = 0; i < count; i++) {
  const o = ph + i * size;
  if (elf.readUInt32LE(o) !== 1) continue;
  const offset = Number(elf.readBigUInt64LE(o + 8)), va = Number(elf.readBigUInt64LE(o + 16)), file = Number(elf.readBigUInt64LE(o + 32)), mem = Number(elf.readBigUInt64LE(o + 40));
  // Linker metadata/header segments may precede virtual address zero.
  if (!(elf.readUInt32LE(o + 4) & 3)) continue;
  if (va < 0 || va + mem > image.length) throw Error('Bridge segment overflow');
  elf.copy(image, va, offset, offset + file);
}
// Nonzero initial data can hide absolute pointers in this flat image.
if (image.subarray(0x10000).some(byte => byte !== 0)) throw Error('Flat bridge data must be zero-initialized; check native pointer arguments');
const entry = Number(elf.readBigUInt64LE(24));
await writeFile(path.join(out, 'gta-bridge.bin'), image);
await writeFile(path.join(assets, 'gta-bridge.bin'), image);
await writeFile(path.join(out, 'gta-bridge.json'), JSON.stringify({ entry, mailbox: 0x10000, size: image.length, sha256: createHash('sha256').update(image).digest('hex') }, null, 2));
console.log({ entry, size: image.length });

}
